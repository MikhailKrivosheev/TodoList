/**
 * Загружает чанк календаря (DayPicker и date-fns). Повторные вызовы не качают файл заново:
 * браузер отдаёт уже загруженный модуль.
 *
 * @returns модуль календаря
 */
export function loadCalendar() {
  return import('./calendar');
}

/**
 * Начинает загрузку календаря заранее — при простое браузера или когда пользователь навёл
 * курсор на кнопку, открывающую календарь. Ошибку загрузки здесь глушим: если сеть пропала,
 * календарь попробует загрузиться ещё раз при открытии и покажет скелетон.
 */
export function preloadCalendar(): void {
  loadCalendar().catch(() => undefined);
}
